const DICTS: Record<Lang, Dict> = { uz, ru, en }

export const LANGS: { id: Lang; label: string }[] = [
  { id: 'uz', label: 'UZ' },
  { id: 'ru', label: 'RU' },
  { id: 'en', label: 'EN' },
]

export function useT(): Dict {
  return DICTS[useStore(settingsStore).lang]
}

/** Joriy tildagi nom (menyu, taom); bo'sh bo'lsa — o'zbekchasi. */
export function useLocalize(): (text: LocalizedText | undefined) => string {
  const { lang } = useStore(settingsStore)
  return (text) => (text ? text[lang] || text.uz : '')
}

export function currentDict(): Dict {
  return DICTS[settingsStore.get().lang]
}

/** Server xato kodi → matn (API.md 3); kodsiz / noma'lum — umumiy matn. */
export function errorText(t: Dict, error: unknown): string {
  const code = typeof error === 'object' && error && 'code' in error ? String((error as { code: unknown }).code) : 'unknown'
  return t.errors[code] ?? t.errors.unknown
}
